pub const CAPTURE_SHARDS_SCHEMA_VERSION: u32 = 1;
pub const SHARD_PLAN_SCHEMA_VERSION: u32 = 1;
pub const DEFAULT_SHARD_MIN_BODIES: usize = 20;
pub const DEFAULT_SHARD_MAX_BODIES: usize = 20;
pub const DEFAULT_SHARD_MAX_AST_NODES: usize = 2_500;

/// Runtime sharding budget policy (default: `20` min / `20` max bodies,
/// `2500` max AST nodes).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ShardConfig {
    pub shard_min_bodies: usize,
    pub shard_max_bodies: usize,
    pub shard_max_ast_nodes: usize,
}

impl Default for ShardConfig {
    fn default() -> Self {
        Self {
            shard_min_bodies: DEFAULT_SHARD_MIN_BODIES,
            shard_max_bodies: DEFAULT_SHARD_MAX_BODIES,
            shard_max_ast_nodes: DEFAULT_SHARD_MAX_AST_NODES,
        }
    }
}

impl ShardConfig {
    pub fn validate(&self) -> Result<(), String> {
        if self.shard_max_bodies == 0 {
            return Err("--shard-max-bodies must be at least 1".to_owned());
        }
        if self.shard_max_ast_nodes == 0 {
            return Err("--shard-max-ast-nodes must be at least 1".to_owned());
        }
        Ok(())
    }
}

/// Condensed strongly connected component in canonical callee-first topological
/// order (`scc_id = 0 .. total_sccs - 1`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SccComponent {
    pub scc_id: usize,
    /// Member `Body.identity` keys sorted lexicographically by UTF-8 bytes.
    pub members: Vec<String>,
    /// `true` iff `members.len() > 1` or the single member has a self-edge.
    pub is_cyclic: bool,
}

/// Single shard entry serialized inside `capture_shards.json`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CaptureShardEntry {
    pub shard_idx: usize,
    pub capture_module: String,
    pub proof_module: String,
    pub capture_sha256: String,
    pub num_bodies: usize,
    pub ast_nodes: usize,
    pub has_cycle: bool,
    pub oversized_scc: bool,
    pub scc_ids: Vec<usize>,
    pub callee_shards: Vec<usize>,
    pub global_def_id_range: [usize; 2],
    pub identities: Vec<String>,
}

/// Authenticated `capture_shards.json` manifest written with `capture.json`
/// whenever sharding is active (`N > shard_min_bodies`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CaptureShardsManifest {
    pub schema_version: u32,
    pub scope: String,
    pub total_bodies: usize,
    pub total_sccs: usize,
    pub cyclic_sccs: usize,
    pub total_shards: usize,
    pub is_lean_module: bool,
    pub id_tree_sha256: String,
    pub shards: Vec<CaptureShardEntry>,
}

/// Nominal static-DAG shard entry inside a checked-in `anneal-shards.json`
/// plan (omitting body-implementation digests so local edits that preserve item
/// sets, SCC/cross-shard call topology, and shard packing remain stable).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ShardPlanEntry {
    pub shard_idx: usize,
    pub capture_module: String,
    pub proof_module: String,
    pub num_bodies: usize,
    pub has_cycle: bool,
    pub oversized_scc: bool,
    pub callee_shards: Vec<usize>,
    pub global_def_id_range: [usize; 2],
    pub identities: Vec<String>,
}

/// Nominal static-DAG `anneal-shards.json` plan checked by
/// `--verify-shard-plan` and generated by `cargo anneal shard-plan --write`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ShardPlan {
    pub schema_version: u32,
    pub sharded: bool,
    pub scope: String,
    pub shard_min_bodies: usize,
    pub shard_max_bodies: usize,
    pub shard_max_ast_nodes: usize,
    pub total_bodies: usize,
    pub total_shards: usize,
    pub id_tree_sha256: Option<String>,
    pub shards: Vec<ShardPlanEntry>,
}

impl ShardPlan {
    pub fn from_unsharded(scope: &ir::Scope, total_bodies: usize, config: ShardConfig) -> Self {
        Self {
            schema_version: SHARD_PLAN_SCHEMA_VERSION,
            sharded: false,
            scope: scope_label(scope).to_owned(),
            shard_min_bodies: config.shard_min_bodies,
            shard_max_bodies: config.shard_max_bodies,
            shard_max_ast_nodes: config.shard_max_ast_nodes,
            total_bodies,
            total_shards: 0,
            id_tree_sha256: None,
            shards: Vec::new(),
        }
    }

    pub fn from_sharded(manifest: &CaptureShardsManifest, config: ShardConfig) -> Self {
        Self {
            schema_version: SHARD_PLAN_SCHEMA_VERSION,
            sharded: true,
            scope: manifest.scope.clone(),
            shard_min_bodies: config.shard_min_bodies,
            shard_max_bodies: config.shard_max_bodies,
            shard_max_ast_nodes: config.shard_max_ast_nodes,
            total_bodies: manifest.total_bodies,
            total_shards: manifest.total_shards,
            id_tree_sha256: Some(manifest.id_tree_sha256.clone()),
            shards: manifest
                .shards
                .iter()
                .map(|s| ShardPlanEntry {
                    shard_idx: s.shard_idx,
                    capture_module: s.capture_module.clone(),
                    proof_module: s.proof_module.clone(),
                    num_bodies: s.num_bodies,
                    has_cycle: s.has_cycle,
                    oversized_scc: s.oversized_scc,
                    callee_shards: s.callee_shards.clone(),
                    global_def_id_range: s.global_def_id_range,
                    identities: s.identities.clone(),
                })
                .collect(),
        }
    }
}

/// Complete sharded capture bundle ready for atomic publication.
pub struct PreparedShards {
    pub root_lean: String,
    pub shard_sources: Vec<(usize, String)>,
    pub manifest: CaptureShardsManifest,
    pub manifest_json: Vec<u8>,
}

fn scope_label(scope: &ir::Scope) -> &'static str {
    match scope {
        ir::Scope::SelectedUnit { .. } => "unit",
        ir::Scope::Crate => "crate",
    }
}
