/// Iterative (explicit-stack) Tarjan SCC condensation followed by Kahn
/// lexicographic min-heap callee-first topological ordering.
///
/// Pre-sorting `identities` and adjacency lists by UTF-8 byte order guarantees
/// canonical output independent of `rustc` hash-table iteration order.
pub fn compute_tarjan_sccs(
    identities: &[String],
    edges: &BTreeMap<String, BTreeSet<String>>,
) -> Result<(Vec<SccComponent>, BTreeMap<String, usize>), String> {
    let mut sorted_nodes: Vec<String> = identities.to_vec();
    sorted_nodes.sort();
    sorted_nodes.dedup();
    if sorted_nodes.len() != identities.len() {
        return Err("duplicate body identities in Tarjan SCC input".to_owned());
    }
    let node_to_idx: BTreeMap<&str, usize> = sorted_nodes
        .iter()
        .enumerate()
        .map(|(i, s)| (s.as_str(), i))
        .collect();
    let n = sorted_nodes.len();
    let mut adj: Vec<Vec<usize>> = vec![Vec::new(); n];
    let mut has_self_edge = vec![false; n];
    for (u_idx, u_id) in sorted_nodes.iter().enumerate() {
        if let Some(callees) = edges.get(u_id) {
            for callee in callees {
                if let Some(&v_idx) = node_to_idx.get(callee.as_str()) {
                    if u_idx == v_idx {
                        has_self_edge[u_idx] = true;
                    }
                    adj[u_idx].push(v_idx);
                }
            }
            adj[u_idx].sort_unstable();
            adj[u_idx].dedup();
        }
    }

    let mut index_counter = 0usize;
    let mut indices: Vec<Option<usize>> = vec![None; n];
    let mut lowlink: Vec<usize> = vec![0; n];
    let mut tarjan_stack: Vec<usize> = Vec::new();
    let mut on_stack: Vec<bool> = vec![false; n];
    let mut raw_sccs: Vec<(Vec<usize>, bool)> = Vec::new();

    for root in 0..n {
        if indices[root].is_some() {
            continue;
        }
        let mut work: Vec<(usize, usize)> = Vec::new();
        indices[root] = Some(index_counter);
        lowlink[root] = index_counter;
        index_counter += 1;
        tarjan_stack.push(root);
        on_stack[root] = true;
        work.push((root, 0));

        while let Some((v, pos)) = work.last().copied() {
            if pos < adj[v].len() {
                let w = adj[v][pos];
                work.last_mut().expect("non-empty work stack").1 = pos + 1;
                if indices[w].is_none() {
                    indices[w] = Some(index_counter);
                    lowlink[w] = index_counter;
                    index_counter += 1;
                    tarjan_stack.push(w);
                    on_stack[w] = true;
                    work.push((w, 0));
                } else if on_stack[w] {
                    let w_idx = indices[w].expect("visited node has index");
                    if w_idx < lowlink[v] {
                        lowlink[v] = w_idx;
                    }
                }
            } else {
                work.pop();
                if let Some(&(parent, _)) = work.last()
                    && lowlink[v] < lowlink[parent]
                {
                    lowlink[parent] = lowlink[v];
                }
                if Some(lowlink[v]) == indices[v] {
                    let mut comp = Vec::new();
                    while let Some(w) = tarjan_stack.pop() {
                        on_stack[w] = false;
                        comp.push(w);
                        if w == v {
                            break;
                        }
                    }
                    comp.sort_unstable();
                    let is_cyclic = comp.len() > 1 || (comp.len() == 1 && has_self_edge[comp[0]]);
                    raw_sccs.push((comp, is_cyclic));
                }
            }
        }
    }

    let num_sccs = raw_sccs.len();
    let mut raw_node_to_scc = vec![0usize; n];
    for (c_idx, (members, _)) in raw_sccs.iter().enumerate() {
        for &m in members {
            raw_node_to_scc[m] = c_idx;
        }
    }

    let mut callee_sets: Vec<BTreeSet<usize>> = vec![BTreeSet::new(); num_sccs];
    let mut caller_sets: Vec<BTreeSet<usize>> = vec![BTreeSet::new(); num_sccs];
    for u in 0..n {
        let cu = raw_node_to_scc[u];
        for &w in &adj[u] {
            let cw = raw_node_to_scc[w];
            if cu != cw {
                callee_sets[cu].insert(cw);
                caller_sets[cw].insert(cu);
            }
        }
    }

    let mut rem_callees: Vec<usize> = callee_sets.iter().map(BTreeSet::len).collect();
    // Min-heap keyed by `(min_member_node_index, raw_scc_idx)`. Because
    // `sorted_nodes` is already sorted by UTF-8 byte order and each `comp` is
    // non-empty and sorted, `comp[0]` orders SCCs identically to `min`.
    let mut heap: BinaryHeap<Reverse<(usize, usize)>> = BinaryHeap::new();
    for (c_idx, &rem) in rem_callees.iter().enumerate() {
        if rem == 0 {
            heap.push(Reverse((raw_sccs[c_idx].0[0], c_idx)));
        }
    }

    let mut ordered_sccs = Vec::with_capacity(num_sccs);
    let mut node_to_scc = BTreeMap::new();
    while let Some(Reverse((_, c_idx))) = heap.pop() {
        let new_id = ordered_sccs.len();
        let (ref member_indices, is_cyclic) = raw_sccs[c_idx];
        let members: Vec<String> = member_indices
            .iter()
            .map(|&idx| {
                let s = sorted_nodes[idx].clone();
                node_to_scc.insert(s.clone(), new_id);
                s
            })
            .collect();
        ordered_sccs.push(SccComponent {
            scc_id: new_id,
            members,
            is_cyclic,
        });
        for &caller_c in &caller_sets[c_idx] {
            rem_callees[caller_c] -= 1;
            if rem_callees[caller_c] == 0 {
                heap.push(Reverse((raw_sccs[caller_c].0[0], caller_c)));
            }
        }
    }

    if ordered_sccs.len() != num_sccs {
        return Err("condensed SCC graph contained a cycle".to_owned());
    }

    Ok((ordered_sccs, node_to_scc))
}

/// Balanced identity decision tree mirroring
/// `Anneal.SccSharding.ByteDecisionTree`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ByteDecisionTree {
    Fail,
    Leaf(usize),
    SplitByte {
        pos: usize,
        threshold: u16,
        lt_branch: Box<Self>,
        ge_branch: Box<Self>,
    },
    SplitTag {
        threshold: u128,
        lt_branch: Box<Self>,
        ge_branch: Box<Self>,
    },
    SplitLex {
        pivot: Vec<u8>,
        le_branch: Box<Self>,
        gt_branch: Box<Self>,
    },
}

fn byte_code_at(bs: &[u8], pos: usize) -> u16 {
    bs.get(pos).copied().map_or(256, u16::from)
}

fn byte_list_tag(bs: &[u8]) -> Option<u128> {
    let mut sum = 0u128;
    for (idx, &b) in bs.iter().enumerate() {
        let w = u128::try_from(idx + 1).ok()?;
        sum = sum.checked_add(w.checked_mul(u128::from(b))?)?;
    }
    Some(sum)
}

fn best_threshold_split<T: Ord + Copy>(sorted_vals: &[T]) -> Option<(T, usize)> {
    let n = sorted_vals.len();
    if n < 2 {
        return None;
    }
    let mut best: Option<(T, usize)> = None;
    for i in 1..n {
        if sorted_vals[i - 1] < sorted_vals[i] {
            let score = i.max(n - i);
            if best.is_none_or(|(_, prev_score)| score < prev_score) {
                best = Some((sorted_vals[i], score));
            }
        }
    }
    best
}

fn join_balanced_lean_lists(chunks: &[String]) -> String {
    match chunks {
        [] => "[]".to_owned(),
        [single] => single.clone(),
        _ => {
            let mid = chunks.len() / 2;
            format!(
                "(_root_.List.append {} {})",
                join_balanced_lean_lists(&chunks[..mid]),
                join_balanced_lean_lists(&chunks[mid..])
            )
        }
    }
}

fn render_u8_list(bytes: &[u8]) -> String {
    if bytes.is_empty() {
        return "[]".to_owned();
    }
    let chunks: Vec<String> = bytes
        .chunks(16)
        .map(|chunk| {
            let items: Vec<String> =
                chunk.iter().map(|b| format!("(_root_.UInt8.ofNat {b})")).collect();
            format!("[{}]", items.join(", "))
        })
        .collect();
    join_balanced_lean_lists(&chunks)
}

impl ByteDecisionTree {
    pub fn eval(&self, bs: &[u8]) -> Option<usize> {
        let mut node = self;
        loop {
            match node {
                Self::Fail => return None,
                Self::Leaf(expected) => return Some(*expected),
                Self::SplitByte { pos, threshold, lt_branch, ge_branch } => {
                    node = if byte_code_at(bs, *pos) < *threshold { lt_branch } else { ge_branch };
                }
                Self::SplitTag { threshold, lt_branch, ge_branch } => {
                    let tag = byte_list_tag(bs)?;
                    node = if tag < *threshold { lt_branch } else { ge_branch };
                }
                Self::SplitLex { pivot, le_branch, gt_branch } => {
                    node = if bs <= pivot.as_slice() { le_branch } else { gt_branch };
                }
            }
        }
    }

    #[cfg(test)]
    pub fn depth(&self) -> usize {
        match self {
            Self::Fail | Self::Leaf(_) => 0,
            Self::SplitByte { lt_branch, ge_branch, .. }
            | Self::SplitTag { lt_branch, ge_branch, .. } => {
                1 + lt_branch.depth().max(ge_branch.depth())
            }
            Self::SplitLex { le_branch, gt_branch, .. } => {
                1 + le_branch.depth().max(gt_branch.depth())
            }
        }
    }

    /// Build a balanced `O(log N)` identity decision tree mapping each
    /// `identities_in_def_order[idx]`'s UTF-8 bytes injectively to `Some(idx)`.
    pub fn build(identities_in_def_order: &[String]) -> Result<Self, String> {
        let items: Vec<(usize, &[u8])> = identities_in_def_order
            .iter()
            .enumerate()
            .map(|(idx, s)| (idx, s.as_bytes()))
            .collect();
        let mut dedup_check = items.clone();
        dedup_check.sort_unstable_by(|a, b| a.1.cmp(b.1));
        for pair in dedup_check.windows(2) {
            if pair[0].1 == pair[1].1 {
                return Err(
                    "duplicate UTF-8 byte sequences in ByteDecisionTree::build".to_owned(),
                );
            }
        }

        fn build_rec(entries: &[(usize, &[u8])]) -> Result<ByteDecisionTree, String> {
            match entries {
                [] => Ok(ByteDecisionTree::Fail),
                [(def_id, _)] => Ok(ByteDecisionTree::Leaf(*def_id)),
                _ => {
                    let n = entries.len();
                    let balance_limit = (n * 3) / 4;
                    let half_ceil = n.div_ceil(2);
                    let max_len = entries.iter().map(|(_, bs)| bs.len()).max().unwrap_or(0);
                    let mut best_pos = 0usize;
                    let mut best_thr = 0u16;
                    let mut best_score = usize::MAX;
                    let mut codes = Vec::with_capacity(n);
                    for pos in 0..=max_len {
                        codes.clear();
                        codes.extend(entries.iter().map(|(_, bs)| byte_code_at(bs, pos)));
                        codes.sort_unstable();
                        if let Some((thr, score)) = best_threshold_split(&codes)
                            && score < best_score
                        {
                            best_score = score;
                            best_pos = pos;
                            best_thr = thr;
                            if score <= half_ceil {
                                break;
                            }
                        }
                    }
                    if best_score <= balance_limit {
                        let (lt_entries, ge_entries): (Vec<_>, Vec<_>) = entries
                            .iter()
                            .copied()
                            .partition(|(_, bs)| byte_code_at(bs, best_pos) < best_thr);
                        if !lt_entries.is_empty() && !ge_entries.is_empty() {
                            return Ok(ByteDecisionTree::SplitByte {
                                pos: best_pos,
                                threshold: best_thr,
                                lt_branch: Box::new(build_rec(&lt_entries)?),
                                ge_branch: Box::new(build_rec(&ge_entries)?),
                            });
                        }
                    }

                    let mut tags = Vec::with_capacity(n);
                    let mut all_tagged = true;
                    for &(_, bs) in entries {
                        match byte_list_tag(bs) {
                            Some(t) => tags.push(t),
                            None => {
                                all_tagged = false;
                                break;
                            }
                        }
                    }
                    if all_tagged {
                        tags.sort_unstable();
                        if let Some((tag_thr, tag_score)) = best_threshold_split(&tags)
                            && tag_score <= balance_limit
                        {
                            let (lt_entries, ge_entries): (Vec<_>, Vec<_>) = entries
                                .iter()
                                .copied()
                                .partition(|(_, bs)| byte_list_tag(bs).unwrap() < tag_thr);
                            if !lt_entries.is_empty() && !ge_entries.is_empty() {
                                return Ok(ByteDecisionTree::SplitTag {
                                    threshold: tag_thr,
                                    lt_branch: Box::new(build_rec(&lt_entries)?),
                                    ge_branch: Box::new(build_rec(&ge_entries)?),
                                });
                            }
                        }
                    }

                    let mut sorted = entries.to_vec();
                    sorted.sort_unstable_by(|a, b| a.1.cmp(b.1));
                    let split_at = n / 2;
                    let pivot = sorted[split_at - 1].1.to_vec();
                    let (le_entries, gt_entries) = sorted.split_at(split_at);
                    Ok(ByteDecisionTree::SplitLex {
                        pivot,
                        le_branch: Box::new(build_rec(le_entries)?),
                        gt_branch: Box::new(build_rec(gt_entries)?),
                    })
                }
            }
        }

        let tree = build_rec(&items)?;
        for &(idx, bs) in &items {
            if tree.eval(bs) != Some(idx) {
                return Err(format!("ByteDecisionTree self-verification failed at DefId {idx}"));
            }
        }
        Ok(tree)
    }

    fn render_lean(&self, indent: usize) -> String {
        match self {
            Self::Fail => "Anneal.SccSharding.ByteDecisionTree.fail".to_owned(),
            Self::Leaf(def_id) => format!("(Anneal.SccSharding.ByteDecisionTree.leaf {def_id})"),
            Self::SplitByte { pos, threshold, lt_branch, ge_branch } => {
                let pad = " ".repeat(indent + 2);
                format!(
                    "(Anneal.SccSharding.ByteDecisionTree.splitByte {pos} {threshold}\n\
                     {pad}{}\n\
                     {pad}{})",
                    lt_branch.render_lean(indent + 2),
                    ge_branch.render_lean(indent + 2)
                )
            }
            Self::SplitTag { threshold, lt_branch, ge_branch } => {
                let pad = " ".repeat(indent + 2);
                format!(
                    "(Anneal.SccSharding.ByteDecisionTree.splitTag {threshold}\n\
                     {pad}{}\n\
                     {pad}{})",
                    lt_branch.render_lean(indent + 2),
                    ge_branch.render_lean(indent + 2)
                )
            }
            Self::SplitLex { pivot, le_branch, gt_branch } => {
                let pad = " ".repeat(indent + 2);
                format!(
                    "(Anneal.SccSharding.ByteDecisionTree.splitLex {}\n\
                     {pad}{}\n\
                     {pad}{})",
                    render_u8_list(pivot),
                    le_branch.render_lean(indent + 2),
                    gt_branch.render_lean(indent + 2)
                )
            }
        }
    }
}

/// Render the deterministic `Proof/IdTree.lean` module source from global
/// `DefId`-ordered `identities`.
pub fn render_id_tree_module(identities_in_def_order: &[String]) -> Result<String, String> {
    let dt = ByteDecisionTree::build(identities_in_def_order)?;
    let mut out = String::from(ID_TREE_PREAMBLE);
    let _ = write!(
        out,
        "def idDecisionTree : Anneal.SccSharding.ByteDecisionTree :=\n\
         \x20 {}\n\n\
         end Proof.IdTree\n\nend\n",
        dt.render_lean(2)
    );
    Ok(out)
}

