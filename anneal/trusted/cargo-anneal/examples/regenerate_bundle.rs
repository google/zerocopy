//! Maintains the verifier's embedded copy of its audited source resources.
//!
//! Run this tool explicitly after changing a bundled source:
//! `cargo run -p cargo-anneal --example regenerate_bundle -- --root .`.
//!
//! CI adds `--check` (and `anneal-audit` verifies parity automatically) to
//! reject stale generated bytes. Ordinary builds never read the source
//! checkout, so the extracted registry package is self-contained.

use cargo_anneal::bundle::{
    render_bundled_resources, render_bundled_theory, validate_bundle_destination,
    validate_theory_bundle_destination,
};
use clap::Parser;
use std::error::Error;
use std::fs;
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};

#[derive(Parser)]
#[command(about = "Regenerate or check the verifier's embedded source resources")]
struct Args {
    /// Names the repository root containing the canonical sources and output.
    #[arg(long)]
    root: PathBuf,
    /// Compares the generated bytes without changing any file.
    #[arg(long)]
    check: bool,
}

fn check_or_write(
    destination: &Path,
    permissions: Option<fs::Permissions>,
    expected: &str,
    check: bool,
) -> Result<(), Box<dyn Error>> {
    // Build and CI callers only compare bytes. Regeneration is an explicit
    // maintenance write, so a stale package cannot silently repair itself
    // while claiming to check the audited canonical sources.
    if check {
        if fs::read(destination)? != expected.as_bytes() {
            return Err(io::Error::other(format!(
                "{} differs from its canonical sources; run regenerate_bundle without --check",
                destination.display()
            ))
            .into());
        }
    } else {
        // Replacing the named file keeps every other hard link to its old
        // inode unchanged. Preserve the destination's permissions on the new
        // file before the same-directory rename makes the update visible.
        let mut temporary = tempfile::NamedTempFile::new_in(
            destination
                .parent()
                .expect("the fixed output path has a parent"),
        )?;
        temporary.write_all(expected.as_bytes())?;
        if let Some(permissions) = permissions {
            temporary.as_file().set_permissions(permissions)?;
        }
        temporary.persist(destination)?;
    }
    Ok(())
}

fn run(args: Args) -> Result<(), Box<dyn Error>> {
    let root = fs::canonicalize(args.root)?;
    let expected_trusted = render_bundled_resources(&root)?;
    let expected_theory = render_bundled_theory(&root)?;
    let (trusted_dest, trusted_perms) = validate_bundle_destination(&root)?;
    let (theory_dest, theory_perms) = validate_theory_bundle_destination(&root)?;
    check_or_write(&trusted_dest, trusted_perms, &expected_trusted, args.check)?;
    check_or_write(&theory_dest, theory_perms, &expected_theory, args.check)?;
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    run(Args::parse())
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use cargo_anneal::bundle::{
        BUNDLE_DESTINATION, PROVENANCE_SOURCES, THEORY_BUNDLE_DESTINATION,
        THEORY_BUNDLE_MANIFEST, TRUSTED_BUNDLE_SOURCES, TheoryBundleEntry, TheoryBundleManifest,
    };
    use cargo_anneal::sha256_bytes;
    use std::os::unix::fs::{PermissionsExt, symlink};
    use std::path::Path;

    fn repository(root: &Path) {
        for source in TRUSTED_BUNDLE_SOURCES {
            let path = root.join(source);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, format!("canonical bytes for {source}\n")).unwrap();
        }
        let theory_sources = [
            "theory/Anneal/MirWp.lean",
            "theory/Anneal/NatBitwise.lean",
        ];
        let mut entries = Vec::new();
        for source in theory_sources {
            let path = root.join(source);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            let bytes = format!("canonical bytes for {source}\n");
            fs::write(&path, &bytes).unwrap();
            entries.push(TheoryBundleEntry {
                path: source.to_owned(),
                sha256: sha256_bytes(bytes.as_bytes()),
            });
        }
        let manifest = TheoryBundleManifest {
            schema_version: 1,
            modules: entries,
        };
        let manifest_path = root.join(THEORY_BUNDLE_MANIFEST);
        fs::create_dir_all(manifest_path.parent().unwrap()).unwrap();
        fs::write(
            manifest_path,
            format!("{}\n", serde_json::to_string_pretty(&manifest).unwrap()),
        )
        .unwrap();
        for source in PROVENANCE_SOURCES {
            let path = root.join(source);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            if *source == "vendor/lean-miri/UPSTREAM_PIN.json" {
                let sample_pin = r#"{
  "repository": "https://github.com/proofs-rs/lean-miri.git",
  "commit": "c92d1d9754c9dd585b6b9d6949ae67e5e4665d6a",
  "upstream_lean_toolchain": "leanprover/lean4:v4.35.0",
  "build_lean_toolchain": "leanprover/lean4:v4.34.1",
  "patched_files": [
    {
      "path": "Miri/Interpreter/Call.lean",
      "upstream_sha256": "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
      "patched_sha256": "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"
    }
  ]
}"#;
                fs::write(path, sample_pin).unwrap();
            } else {
                fs::write(path, format!("canonical bytes for {source}\n")).unwrap();
            }
        }
        fs::create_dir_all(root.join(BUNDLE_DESTINATION).parent().unwrap()).unwrap();
    }

    #[test]
    fn regeneration_preserves_outside_hard_link_and_output_permissions() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside.rs");
        let original = b"outside file must remain unchanged\n";
        fs::write(&outside, original).unwrap();
        fs::set_permissions(&outside, fs::Permissions::from_mode(0o640)).unwrap();
        let destination = root.join(BUNDLE_DESTINATION);
        fs::hard_link(&outside, &destination).unwrap();

        let outside_theory = fixture.path().join("outside.json");
        fs::write(&outside_theory, original).unwrap();
        fs::set_permissions(&outside_theory, fs::Permissions::from_mode(0o640)).unwrap();
        let theory_dest = root.join(THEORY_BUNDLE_DESTINATION);
        fs::hard_link(&outside_theory, &theory_dest).unwrap();

        run(Args {
            root: root.clone(),
            check: false,
        })
        .unwrap();

        assert_eq!(fs::read(&outside).unwrap(), original);
        assert_eq!(fs::read(&outside_theory).unwrap(), original);
        assert_eq!(
            fs::read(&destination).unwrap(),
            render_bundled_resources(&root).unwrap().as_bytes()
        );
        assert_eq!(
            fs::read(&theory_dest).unwrap(),
            render_bundled_theory(&root).unwrap().as_bytes()
        );
        assert_eq!(
            fs::metadata(destination).unwrap().permissions().mode() & 0o777,
            0o640
        );
        assert_eq!(
            fs::metadata(theory_dest).unwrap().permissions().mode() & 0o777,
            0o640
        );
    }

    #[test]
    fn both_modes_reject_symlinked_output_without_changing_its_target() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside.rs");
        fs::write(&outside, b"outside sentinel\n").unwrap();
        symlink(&outside, root.join(BUNDLE_DESTINATION)).unwrap();

        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular file"), "{error}");
            assert_eq!(fs::read(&outside).unwrap(), b"outside sentinel\n");
        }
        fs::remove_file(root.join(BUNDLE_DESTINATION)).unwrap();

        let outside_theory = fixture.path().join("outside.json");
        fs::write(&outside_theory, b"outside sentinel\n").unwrap();
        symlink(&outside_theory, root.join(THEORY_BUNDLE_DESTINATION)).unwrap();
        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular file"), "{error}");
            assert_eq!(fs::read(&outside_theory).unwrap(), b"outside sentinel\n");
        }
    }

    #[test]
    fn both_modes_reject_symlinked_output_parent() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside = fixture.path().join("outside");
        fs::create_dir(&outside).unwrap();
        let source_directory = root.join(BUNDLE_DESTINATION).parent().unwrap().to_owned();
        fs::remove_dir(&source_directory).unwrap();
        symlink(&outside, source_directory).unwrap();

        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular directory"), "{error}");
            assert_eq!(fs::read_dir(&outside).unwrap().count(), 0);
        }
    }

    #[test]
    fn both_modes_reject_symlinked_bundle_source_and_parent() {
        let fixture = tempfile::tempdir().unwrap();
        let root = fixture.path().join("repository");
        repository(&root);
        let outside_file = fixture.path().join("outside.lean");
        fs::write(&outside_file, b"-- outside\n").unwrap();

        // 1. Symlinked leaf source file listed in `THEORY_BUNDLE_MANIFEST` is rejected.
        let leaf = root.join("theory/Anneal/MirWp.lean");
        fs::remove_file(&leaf).unwrap();
        symlink(&outside_file, &leaf).unwrap();
        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular file"), "{error}");
        }
        fs::remove_file(&leaf).unwrap();
        fs::write(&leaf, b"canonical bytes for theory/Anneal/MirWp.lean\n").unwrap();

        // 2. Symlinked parent directory of a theory source file is rejected.
        let outside_dir = fixture.path().join("outside-theory");
        fs::create_dir_all(&outside_dir).unwrap();
        fs::write(
            outside_dir.join("MirWp.lean"),
            b"canonical bytes for theory/Anneal/MirWp.lean\n",
        )
        .unwrap();
        let parent_dir = root.join("theory/Anneal");
        fs::remove_dir_all(&parent_dir).unwrap();
        symlink(&outside_dir, &parent_dir).unwrap();
        for check in [false, true] {
            let error = run(Args {
                root: root.clone(),
                check,
            })
            .unwrap_err();
            assert!(error.to_string().contains("regular directory"), "{error}");
        }
    }
}
