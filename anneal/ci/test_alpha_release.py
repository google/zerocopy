    def test_crate_verifier_bounds_memory_on_sparse_oversized_and_corrupt_streams(
        self,
    ) -> None:
        version = "0.2.0-alpha.7"
        prefix = f"cargo-anneal-{version}/"

        # 1. Corrupt deflate stream after valid gzip header raises ValueError.
        good = _make_crate_bytes(version=version, commit="c" * 40, sha256="3" * 64)
        corrupt_deflate = good[:10] + b"\x01\xff\xff\x00\x00\xde\xad\xbe\xef"
        with self.assertRaisesRegex(ValueError, "corrupt .crate archive"):
            inspect_crate_archive(corrupt_deflate, version=version)

        # 2. Crafted USTAR member declaring 512 MiB fails before
        # reading/allocating.
        huge = tarfile.TarInfo(f"{prefix}src/huge.bin")
        huge.type = tarfile.REGTYPE
        huge.size = 512 * 1024 * 1024
        oversized_tar = huge.tobuf(tarfile.USTAR_FORMAT) + b"\x00" * 1024
        oversized_crate = gzip.compress(oversized_tar, mtime=0)
        tracemalloc.start()
        try:
            with self.assertRaisesRegex(ValueError, "exceeds 64 MiB limit"):
                inspect_crate_archive(oversized_crate, version=version)
            _, peak_bytes = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        self.assertLess(peak_bytes, 4 * 1024 * 1024)

        # 3. PAX sparse entry (isreg() == True, issparse() == True) is rejected.
        def pax_record(key: str, value: str) -> bytes:
            body = f" {key}={value}\n".encode("utf-8")
            n = len(body) + 1
            while True:
                line = f"{n}".encode("ascii") + body
                if len(line) == n:
                    return line
                n = len(line)

        pax_data = (
            pax_record("GNU.sparse.major", "1")
            + pax_record("GNU.sparse.minor", "0")
            + pax_record("GNU.sparse.name", f"{prefix}src/sparse.bin")
            + pax_record("GNU.sparse.realsize", str(128 * 1024 * 1024))
        )
        pax_hdr = tarfile.TarInfo("PaxHeader/sparse.bin")
        pax_hdr.type = tarfile.XHDTYPE
        pax_hdr.size = len(pax_data)
        sparse_reg = tarfile.TarInfo(f"{prefix}src/sparse.bin")
        sparse_reg.type = tarfile.REGTYPE
        sparse_payload = b"1\n0\n0\n"
        sparse_reg.size = len(sparse_payload)
        pax_pad = b"\x00" * ((512 - len(pax_data) % 512) % 512)
        reg_pad = b"\x00" * ((512 - len(sparse_payload) % 512) % 512)
        sparse_tar = (
            pax_hdr.tobuf(tarfile.PAX_FORMAT)
            + pax_data
            + pax_pad
            + sparse_reg.tobuf(tarfile.PAX_FORMAT)
            + sparse_payload
            + reg_pad
            + b"\x00" * 1024
        )
        sparse_crate = gzip.compress(sparse_tar, mtime=0)
        tracemalloc.start()
        try:
            with self.assertRaisesRegex(ValueError, "non-regular tar entry"):
                inspect_crate_archive(sparse_crate, version=version)
            _, sparse_peak = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        self.assertLess(sparse_peak, 4 * 1024 * 1024)

        # 4. Cumulative payload size (> remaining) fails before allocation.
        first = tarfile.TarInfo(f"{prefix}src/first.bin")
        first.type = tarfile.REGTYPE
        first_payload = b"x" * 1024
        first.size = len(first_payload)
        second = tarfile.TarInfo(f"{prefix}src/second.bin")
        second.type = tarfile.REGTYPE
        second.size = 64 * 1024 * 1024
        cumulative_tar = (
            first.tobuf(tarfile.USTAR_FORMAT)
            + first_payload
            + second.tobuf(tarfile.USTAR_FORMAT)
            + b"\x00" * 1024
        )
        cumulative_crate = gzip.compress(cumulative_tar, mtime=0)
        tracemalloc.start()
        try:
            with self.assertRaisesRegex(ValueError, "exceeds 64 MiB limit"):
                inspect_crate_archive(cumulative_crate, version=version)
            _, cum_peak = tracemalloc.get_traced_memory()
        finally:
            tracemalloc.stop()
        self.assertLess(cum_peak, 4 * 1024 * 1024)

        # 5. Uncompressed stream > 64 MiB fails closed via chunked reader.
        gz_bomb = gzip.compress(b"\x00" * (64 * 1024 * 1024 + 1), mtime=0)
        with self.assertRaisesRegex(ValueError, "exceeds 64 MiB limit"):
            inspect_crate_archive(gz_bomb, version=version)

    def test_resolve_fresh_monotonicity_first_parent_and_shallow_guards(self) -> None:
        with tempfile.TemporaryDirectory(prefix="anneal-resolve-") as tmp:
            fx = RepoFixture(Path(tmp))
            c1 = fx.initial_commit
            fx.tag_annotated("anneal-v0.2.0-alpha.5", c1)
            c2 = fx.commit_all("add scalar feature", touch_file="anneal/a.txt")
            # Merge a side branch via `--no-ff` so `side_sha` is an ancestor of
            # `origin/main` but NOT on `origin/main`'s first-parent history.
            fx.git("checkout", "-q", "-b", "feature", c1)
            side_sha = fx.commit_all("side commit", touch_file="anneal/side.txt")
            fx.git("checkout", "-q", "main")
            fx.git("merge", "--quiet", "--no-ff", "feature", "-m", "merge feature")
            c3 = fx.git("rev-parse", "HEAD")
            fx.push_main()

            def crates_api_with(versions: list[dict]) -> tuple[int, bytes]:
                return 200, json.dumps({"versions": versions}).encode("utf-8")

            # A colliding branch name (`refs/heads/anneal-v0.2.0-alpha.5`) must
            # not break `refs/tags/anneal-v*` enumeration (`refname:lstrip=2`).
            fx.git("branch", "anneal-v0.2.0-alpha.5", c1)

            # Historical untagged crates (`0.2.0-alpha.1` below
            # `anneal-v0.2.0-alpha.5`) do not block fresh releases.
            http_map = {
                CRATES_API_URL: crates_api_with(
                    [
                        {"num": "0.2.0-alpha.5", "yanked": False},
                        {"num": "0.2.0-alpha.1", "yanked": False},
                    ]
                )
            }
            res = resolve_and_validate(
                fx.repo,
                version="0.2.0-alpha.7",
                default_sha=c3,
                http_get=lambda url: http_map[url],
            )
            self.assertFalse(res.already_published)
            self.assertEqual(res.commit, c3)

            # Explicit first-parent historical commit `c2` is also valid.
            res_c2 = resolve_and_validate(
                fx.repo,
                version="0.2.0-alpha.7",
                commit=c2,
                default_sha=c3,
                http_get=lambda url: http_map[url],
            )
            self.assertEqual(res_c2.commit, c2)

            # Side-branch commit `side_sha` is rejected.
            with self.assertRaisesRegex(ValueError, "first-parent"):
                resolve_and_validate(
                    fx.repo,
                    version="0.2.0-alpha.7",
                    commit=side_sha,
                    default_sha=c3,
                    http_get=lambda url: http_map[url],
                )

            # Re-releasing at an already tagged commit `c1` is rejected.
            with self.assertRaisesRegex(ValueError, "already tagged"):
                resolve_and_validate(
                    fx.repo,
                    version="0.2.0-alpha.7",
                    commit=c1,
                    default_sha=c3,
                    http_get=lambda url: http_map[url],
                )

            # Older version (`0.2.0-alpha.4` < `0.2.0-alpha.5`) is rejected by
            # SemVer monotonicity; non-`0.2.0-alpha.<N>` pre-releases (including
            # `+build` suffixes) fail the version gate.
            with self.assertRaisesRegex(ValueError, "strictly exceed"):
                resolve_and_validate(
                    fx.repo,
                    version="0.2.0-alpha.4",
                    default_sha=c3,
                    http_get=lambda url: http_map[url],
                )
            for bad_ver in ("0.2.0-alpha.5+b1", "1.0.0-rc.1"):
                with self.subTest(bad_ver=bad_ver), self.assertRaisesRegex(
                    ValueError, r"0\.2\.0-alpha\.<N>"
                ):
                    resolve_and_validate(
                        fx.repo,
                        version=bad_ver,
                        default_sha=c3,
                        http_get=lambda url: http_map[url],
                    )
            for empty_kw in (
                {"expected_sha256": ""},
                {"expected_source_sha256": ""},
            ):
                with self.subTest(empty_kw=empty_kw), self.assertRaisesRegex(
                    ValueError, "invalid nonzero 64-hex"
                ):
                    resolve_and_validate(
                        fx.repo,
                        version="0.2.0-alpha.7",
                        default_sha=c3,
                        http_get=lambda url: http_map[url],
                        **empty_kw,
                    )

            # An already-existing `anneal-v<V>` Git tag without a crates.io
            # release fails closed immediately.
            fx.tag_annotated("anneal-v0.2.0-alpha.6", c2)
            with self.assertRaisesRegex(ValueError, "already exists"):
                resolve_and_validate(
                    fx.repo,
                    version="0.2.0-alpha.6",
                    default_sha=c3,
                    http_get=lambda url: http_map[url],
                )

            # Shallow clone fails closed via `ensure_not_shallow`.
            shallow_dir = Path(tmp) / "shallow"
            subprocess.run(
                [
                    "git",
                    "clone",
                    "--quiet",
                    "--depth=1",
                    f"file://{fx.origin}",
                    str(shallow_dir),
                ],
                check=True,
            )
            with self.assertRaisesRegex(ValueError, "shallow"):
                resolve_and_validate(
                    shallow_dir,
                    version="0.2.0-alpha.7",
                    default_sha=c3,
                    http_get=lambda url: http_map[url],
                )

