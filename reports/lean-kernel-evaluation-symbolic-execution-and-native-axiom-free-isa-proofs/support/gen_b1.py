#!/usr/bin/env python3
"""Generate probe B1 files: kernel evaluation of a Sail-style monadic RV64 step function
(EStateM over a state record) with different register-file representations.
Program (decoded from real RV64 encodings at every step):
   0: addi x5, x0, 0
   4: addi x6, x0, K
   8: addi x7, x0, 3
  12: add  x5, x5, x6
  16: mul  x8, x5, x7
  20: addi x6, x6, -1
  24: bne  x6, x0, -12
"""
import os, sys
K = 400
def addi(rd, rs1, imm): return ((imm & 0xfff) << 20) | (rs1 << 15) | (rd << 7) | 0x13
def add(rd, rs1, rs2): return (rs2 << 20) | (rs1 << 15) | (rd << 7) | 0x33
def mul(rd, rs1, rs2): return (1 << 25) | (rs2 << 20) | (rs1 << 15) | (rd << 7) | 0x33
def bne(rs1, rs2, off):
    o = off & 0x1fff
    return (((o >> 12) & 1) << 31) | (((o >> 5) & 0x3f) << 25) | (rs2 << 20) | (rs1 << 15) | (1 << 12) | (((o >> 1) & 0xf) << 8) | (((o >> 11) & 1) << 7) | 0x63
PROG = [addi(5,0,0), addi(6,0,K), addi(7,0,3), add(5,5,6), mul(8,5,7), addi(6,6,-1), bne(6,0,-12)]
M64 = (1 << 64) - 1

def sim(n):
    r = [0]*32; pc = 0
    for _ in range(n):
        w = PROG[pc//4]
        opc = w & 0x7f; rd = (w >> 7) & 31; rs1 = (w >> 15) & 31; rs2 = (w >> 20) & 31
        f3 = (w >> 12) & 7; f7 = w >> 25
        if opc == 0x13:
            imm = (w >> 20) & 0xfff
            if imm & 0x800: imm -= 0x1000
            if rd: r[rd] = (r[rs1] + imm) & M64
            pc += 4
        elif opc == 0x33 and f7 == 0:
            if rd: r[rd] = (r[rs1] + r[rs2]) & M64
            pc += 4
        elif opc == 0x33 and f7 == 1:
            if rd: r[rd] = (r[rs1] * r[rs2]) & M64
            pc += 4
        elif opc == 0x63:
            imm = (((w >> 31) & 1) << 12) | (((w >> 7) & 1) << 11) | (((w >> 25) & 0x3f) << 5) | (((w >> 8) & 0xf) << 1)
            if imm & 0x1000: imm -= 0x2000
            pc = pc + imm if r[rs1] != r[rs2] else pc + 4
        else:
            raise Exception("illegal")
    return r[5] + r[8] * 1  # observable: x5 + x8 (as Nat, < 2^65)

REGFILES = {
 "fun": dict(imports="", ty="Nat → BitVec 64",
    get="fun r i => if i = 0 then 0 else r i",
    set="fun r i v => fun j => if j = i then v else r j",
    init="fun _ => 0"),
 "array": dict(imports="", ty="Array (BitVec 64)",
    get="fun r i => if i = 0 then 0 else r.getD i 0",
    set="fun r i v => r.setIfInBounds i v",
    init="Array.replicate 32 0"),
 "assoc": dict(imports="", ty="List (Nat × BitVec 64)",
    get="fun r i => if i = 0 then 0 else ((r.lookup i).getD 0)",
    set="fun r i v => (i, v) :: r",
    init="[]"),
 "hashmap": dict(imports="import Std.Data.HashMap", ty="Std.HashMap Nat (BitVec 64)",
    get="fun r i => if i = 0 then 0 else ((r.get? i).getD 0)",
    set="fun r i v => r.insert i v",
    init="{}"),
 "exthashmap": dict(imports="import Std.Data.ExtHashMap", ty="Std.ExtHashMap Nat (BitVec 64)",
    get="fun r i => if i = 0 then 0 else ((r.get? i).getD 0)",
    set="fun r i v => r.insert i v",
    init="{}"),
}

TEMPLATE = r'''/- Probe B1 (generated by gen_b1.py): kernel evaluation of a Sail-style monadic RV64
   interpreter. Register file representation: {name}. Steps: {n}. Tactic: {tac}. -/
{imports}
set_option maxRecDepth 100000

abbrev Regs := {ty}
def Regs.get : Regs → Nat → BitVec 64 := {get}
def Regs.set : Regs → Nat → BitVec 64 → Regs := {set}
def Regs.init : Regs := {init}

structure St where
  regs : Regs
  pc : BitVec 64

inductive Err | fetch | illegal

/-- Sail-V1-style monad: `EStateM (Error) (State)`. -/
abbrev M := EStateM Err St

def code : List (BitVec 32) := [{prog}]

def rdReg (i : Nat) : M (BitVec 64) := do return (← get).regs.get i
def wrReg (i : Nat) (v : BitVec 64) : M Unit :=
  if i = 0 then pure () else modify fun s => {{ s with regs := s.regs.set i v }}
def advance : M Unit := modify fun s => {{ s with pc := s.pc + 4 }}

def step : M Unit := do
  let s ← get
  match code[s.pc.toNat / 4]? with
  | none => throw .fetch
  | some w =>
    let opc := w.extractLsb 6 0
    let rd := (w.extractLsb 11 7).toNat
    let rs1 := (w.extractLsb 19 15).toNat
    let rs2 := (w.extractLsb 24 20).toNat
    let f3 := w.extractLsb 14 12
    let f7 := w.extractLsb 31 25
    if opc = 0x13#7 ∧ f3 = 0#3 then
      let imm : BitVec 64 := (w.extractLsb 31 20).signExtend 64
      let a ← rdReg rs1
      wrReg rd (a + imm); advance
    else if opc = 0x33#7 ∧ f3 = 0#3 ∧ f7 = 0#7 then
      let a ← rdReg rs1; let b ← rdReg rs2
      wrReg rd (a + b); advance
    else if opc = 0x33#7 ∧ f3 = 0#3 ∧ f7 = 1#7 then
      let a ← rdReg rs1; let b ← rdReg rs2
      wrReg rd (a * b); advance
    else if opc = 0x63#7 ∧ f3 = 1#3 then
      let imm : BitVec 13 :=
        w.extractLsb 31 31 ++ w.extractLsb 7 7 ++ w.extractLsb 30 25 ++ w.extractLsb 11 8 ++ 0#1
      let a ← rdReg rs1; let b ← rdReg rs2
      if a ≠ b then modify fun s => {{ s with pc := s.pc + imm.signExtend 64 }} else advance
    else throw .illegal

/-- Structural fuel recursion. -/
def run : Nat → M Unit
  | 0 => pure ()
  | n + 1 => do step; run n

def s0 : St := {{ regs := Regs.init, pc := 0 }}

def result (n : Nat) : Nat :=
  match (run n).run s0 with
  | .ok _ s => (s.regs.get 5).toNat + (s.regs.get 8).toNat
  | .error _ _ => 0

theorem b1_result : result {n} = {expected} := by {tac}
#print axioms b1_result
'''

def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    prog = ", ".join(f"0x{w:08x}#32" for w in PROG)
    for name, rf in REGFILES.items():
        for n in [1, 10, 100, 1000]:
            for tac in ["decide +kernel", "rfl", "decide"]:
                tname = {"decide +kernel": "dk", "rfl": "rfl", "decide": "dec"}[tac]
                fn = os.path.join(out, f"B1_{name}_{n}_{tname}.lean")
                with open(fn, "w") as f:
                    f.write(TEMPLATE.format(name=name, n=n, tac=tac, prog=prog, expected=sim(n), **rf))
    print("expected:", {n: sim(n) for n in [1, 10, 100, 1000]})

if __name__ == "__main__":
    main()
