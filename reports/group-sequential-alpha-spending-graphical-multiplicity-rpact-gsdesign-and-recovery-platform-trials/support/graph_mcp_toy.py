#!/usr/bin/env python3
"""TOY checks (Python re-implementation, not graphicalMCP) of two properties of
graphical multiple comparison procedures (Bretz, Maurer, Brannath, Posch 2009):

 (1) Order invariance: applying the Bretz et al. update rule
        w_l <- w_l + w_j g_jl ;  g_lk <- (g_lk + g_lj g_jk) / (1 - g_lj g_jl)
     sequentially, the final set of rejected hypotheses of the sequentially
     rejective Bonferroni procedure does not depend on which rejectable
     hypothesis is removed first.
 (2) Shortcut == closure: for Bonferroni local tests, the sequentially
     rejective (shortcut) procedure rejects exactly the hypotheses rejected by
     the closed test whose intersection weights are generated by removing the
     complement hypotheses from the graph with the same update rule.
The update rule above is the one in openpharma/graphicalMCP R/graph_update.R
(lines 131-153 at the pinned revision); the 'denominator <= 0 -> transition 0'
guard is reproduced.
Usage: python3 graph_mcp_toy.py [graphs] [m] [seed]   (standard library only)
"""
import itertools
import random
import sys


def update(w, g, j):
    m = len(w)
    nw = list(w)
    ng = [row[:] for row in g]
    for l in range(m):
        if l == j:
            continue
        nw[l] = w[l] + w[j] * g[j][l]
        den = 1 - g[l][j] * g[j][l]
        for k in range(m):
            if l == k or den <= 0:
                ng[l][k] = 0.0
            else:
                ng[l][k] = (g[l][k] + g[l][j] * g[j][k]) / den
    nw[j] = 0.0
    for k in range(m):
        ng[j][k] = 0.0
        ng[k][j] = 0.0
    return nw, ng


def shortcut(w, g, p, alpha, rng=None):
    active = set(range(len(w)))
    rejected = []
    while True:
        cand = [j for j in active if w[j] > 0 and p[j] <= w[j] * alpha]
        if not cand:
            return set(rejected)
        j = rng.choice(cand) if rng else min(cand)
        rejected.append(j)
        active.discard(j)
        w, g = update(w, g, j)


def closure(w0, g0, p, alpha):
    m = len(w0)
    rej_inter = {}
    for r in range(1, m + 1):
        for J in itertools.combinations(range(m), r):
            w, g = list(w0), [row[:] for row in g0]
            for j in range(m):
                if j not in J:
                    w, g = update(w, g, j)
            rej_inter[J] = any(p[j] <= w[j] * alpha for j in J if w[j] > 0)
    out = set()
    for i in range(m):
        if all(v for J, v in rej_inter.items() if i in J):
            out.add(i)
    return out


def random_graph(rng, m):
    w = [rng.random() for _ in range(m)]
    s = sum(w)
    w = [x / s for x in w]
    g = []
    for i in range(m):
        row = [0.0 if j == i else rng.random() * (rng.random() < 0.8) for j in range(m)]
        s = sum(row)
        tot = rng.choice([1.0, 1.0, 1.0, rng.random()])  # mostly complete graphs
        row = [x / s * tot if s > 0 else 0.0 for x in row]
        g.append(row)
    return w, g


def main():
    graphs = int(sys.argv[1]) if len(sys.argv) > 1 else 20000
    m = int(sys.argv[2]) if len(sys.argv) > 2 else 4
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 20261120
    rng = random.Random(seed)
    alpha = 0.025
    order_mismatch = closure_mismatch = nonempty = 0
    for _ in range(graphs):
        w, g = random_graph(rng, m)
        p = [rng.random() ** 3 * 0.1 for _ in range(m)]  # skewed small p-values
        base = shortcut(w, g, p, alpha)
        nonempty += bool(base)
        for _ in range(3):
            if shortcut(w, g, p, alpha, rng) != base:
                order_mismatch += 1
                break
        if closure(w, g, p, alpha) != base:
            closure_mismatch += 1
    print(f'graphs={graphs} m={m} seed={seed} alpha={alpha}')
    print(f'graphs with >=1 rejection: {nonempty}')
    print(f'order-dependence cases (3 random orders each): {order_mismatch}')
    print(f'shortcut vs closure (Bonferroni) disagreements: {closure_mismatch}')


if __name__ == '__main__':
    main()
