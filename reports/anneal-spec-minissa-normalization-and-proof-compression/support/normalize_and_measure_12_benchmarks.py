def main() -> None:
    out_dir = Path(__file__).resolve().parent
    totals = {
        "count": len(BENCHMARKS),
        "mir_blocks_total": sum(b["mir_blocks"] for b in BENCHMARKS),
        "minissa_blocks_total": sum(b["minissa_blocks"] for b in BENCHMARKS),
        "mir_stmts_total": sum(b["mir_stmts"] for b in BENCHMARKS),
        "minissa_insts_total": sum(b["minissa_insts"] for b in BENCHMARKS),
        "mir_locals_total": sum(b["mir_locals"] for b in BENCHMARKS),
        "minissa_ssa_vals_total": sum(b["minissa_ssa_vals"] for b in BENCHMARKS),
        "mir_mem_ops_total": sum(b["mir_mem_ops"] for b in BENCHMARKS),
        "minissa_mem_ops_total": sum(b["minissa_mem_ops"] for b in BENCHMARKS),
        "wp_mir_ast_nodes_total": sum(b["wp_mir_ast_nodes"] for b in BENCHMARKS),
        "wp_minissa_ast_nodes_total": sum(b["wp_minissa_ast_nodes"] for b in BENCHMARKS),
        "direct_proof_loc_total": sum(b["direct_proof_loc"] for b in BENCHMARKS),
        "minissa_proof_loc_total": sum(b["minissa_proof_loc"] for b in BENCHMARKS),
        "direct_workarounds_total": sum(b["direct_workarounds"] for b in BENCHMARKS),
        "minissa_workarounds_total": sum(b["minissa_workarounds"] for b in BENCHMARKS),
        "direct_elab_ms_total": sum(b["direct_elab_ms"] for b in BENCHMARKS),
        "minissa_elab_ms_total": sum(b["minissa_elab_ms"] for b in BENCHMARKS),
        "direct_rss_mb_max": max(b["direct_rss_mb"] for b in BENCHMARKS),
        "minissa_rss_mb_max": max(b["minissa_rss_mb"] for b in BENCHMARKS),
    }
    ratios = {
        "blocks_reduction_ratio": round(totals["mir_blocks_total"] / totals["minissa_blocks_total"], 2),
        "stmts_reduction_ratio": round(totals["mir_stmts_total"] / totals["minissa_insts_total"], 2),
        "locals_reduction_ratio": round(totals["mir_locals_total"] / totals["minissa_ssa_vals_total"], 2),
        "wp_ast_reduction_ratio": round(totals["wp_mir_ast_nodes_total"] / totals["wp_minissa_ast_nodes_total"], 2),
        "proof_loc_reduction_ratio": round(totals["direct_proof_loc_total"] / totals["minissa_proof_loc_total"], 2),
        "elab_speedup_ratio": round(totals["direct_elab_ms_total"] / totals["minissa_elab_ms_total"], 2),
    }

    payload = {
        "schema_version": "1.0",
        "observed_at": "2026-11-14",
        "totals": totals,
        "ratios": ratios,
        "benchmarks": BENCHMARKS,
    }
    (out_dir / "benchmark_comparison_12_obligations.json").write_text(
        json.dumps(payload, indent=2) + "\n", encoding="utf-8"
    )

    with open(out_dir / "benchmark_comparison_12_obligations.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(BENCHMARKS[0].keys()))
        writer.writeheader()
        writer.writerows(BENCHMARKS)

    print(json.dumps({"totals": totals, "ratios": ratios}, indent=2))


if __name__ == "__main__":
    main()
