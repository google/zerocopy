// Execution cross-check for the toy niche-layout model.
//
// Prints `size_of` for the payloads and option-like enums the model discusses, transmutes
// all-zero and nonzero byte arrays into `Option<NonZeroU32>`, and reads the observed byte
// patterns of a few values whose representation is NOT guaranteed (marked "observed").
//
// The last section prints sizes behind some non-claims: an enum whose extra variant is
// uninhabited, `UnsafeCell` (which disables niches), `char`, and enums with 254 or 255
// dataless variants next to a `bool` or `(bool, bool)` payload (how many niche values the
// compiler actually uses).
//
// This is evidence about one compiler build and target, not a proof and not a guarantee.
// Build and run: rustc -O niche_probe.rs -o niche_probe && ./niche_probe

use std::cell::UnsafeCell;
use std::convert::Infallible;
use std::mem::{align_of, size_of, transmute};
use std::num::{NonZeroU32, NonZeroU8};

fn byte_of<T>(v: &T) -> u8 {
    // Reads the first byte of `v`. Only used on 1-byte values whose observed
    // representation has no uninitialized bytes.
    assert_eq!(size_of::<T>(), 1);
    unsafe { *(v as *const T as *const u8) }
}


