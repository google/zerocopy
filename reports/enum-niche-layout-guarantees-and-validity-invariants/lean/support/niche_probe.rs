fn main() {
    println!("== sizes (bytes) and alignments ==");
    println!("u32: size {} align {}", size_of::<u32>(), align_of::<u32>());
    println!("NonZeroU32: size {} align {}", size_of::<NonZeroU32>(), align_of::<NonZeroU32>());
    println!(
        "Option<NonZeroU32>: size {} align {}",
        size_of::<Option<NonZeroU32>>(),
        align_of::<Option<NonZeroU32>>()
    );
    println!("u8: size {}", size_of::<u8>());
    println!("NonZeroU8: size {}", size_of::<NonZeroU8>());
    println!("Option<NonZeroU8>: size {}", size_of::<Option<NonZeroU8>>());
    println!("Option<Option<NonZeroU8>>: size {}", size_of::<Option<Option<NonZeroU8>>>());
    println!("Option<u8>: size {}", size_of::<Option<u8>>());
    println!("&u32: size {}", size_of::<&u32>());
    println!("Option<&u32>: size {}", size_of::<Option<&u32>>());
    println!("Box<u32>: size {}", size_of::<Box<u32>>());
    println!("Option<Box<u32>>: size {}", size_of::<Option<Box<u32>>>());
    println!("fn(): size {}", size_of::<fn()>());
    println!("Option<fn()>: size {}", size_of::<Option<fn()>>());
    println!("bool: size {}", size_of::<bool>());
    println!("Option<bool>: size {}  (observed; not guaranteed)", size_of::<Option<bool>>());
    println!(
        "Option<Option<bool>>: size {}  (observed; not guaranteed)",
        size_of::<Option<Option<bool>>>()
    );

    println!("== Option<NonZeroU32> from bytes (guaranteed cases) ==");
    // Guaranteed: transmuting [0u8; size_of::<T>()] to Option<T> produces None.
    let z: Option<NonZeroU32> = unsafe { transmute::<[u8; 4], Option<NonZeroU32>>([0u8; 4]) };
    println!("transmute([0u8; 4]) = {:?}", z);
    // Guaranteed: transmuting None to bytes produces [0u8; 4].
    let nb: [u8; 4] = unsafe { transmute::<Option<NonZeroU32>, [u8; 4]>(None) };
    println!("transmute(None::<NonZeroU32>) = {:?}", nb);
    // Guaranteed: transmuting a valid NonZeroU32 value t to Option<NonZeroU32> gives Some(t).
    for x in [1u32, 2, 0x0102_0304, u32::MAX] {
        let o: Option<NonZeroU32> =
            unsafe { transmute::<[u8; 4], Option<NonZeroU32>>(x.to_ne_bytes()) };
        println!("transmute({:#010x}.to_ne_bytes()) = {:?}", x, o);
    }

    println!("== observed byte patterns (not guaranteed) ==");
    let ob_none: Option<bool> = None;
    println!(
        "Option<bool>: None = {:#04x}, Some(false) = {:#04x}, Some(true) = {:#04x}",
        byte_of(&ob_none),
        byte_of(&Some(false)),
        byte_of(&Some(true))
    );
    let oob: [Option<Option<bool>>; 2] = [None, Some(None)];
    println!(
        "Option<Option<bool>>: None = {:#04x}, Some(None) = {:#04x}",
        byte_of(&oob[0]),
        byte_of(&oob[1])
    );

    println!("== layout facts referenced by the non-claims (observed; not guaranteed) ==");
    println!("Result<u8, Infallible>: size {}", size_of::<Result<u8, Infallible>>());
    println!("UnsafeCell<NonZeroU32>: size {}", size_of::<UnsafeCell<NonZeroU32>>());
    println!(
        "Option<UnsafeCell<NonZeroU32>>: size {}",
        size_of::<Option<UnsafeCell<NonZeroU32>>>()
    );
    println!("char: size {}", size_of::<char>());
    println!("Option<char>: size {}", size_of::<Option<char>>());
    println!("(bool, bool): size {}", size_of::<(bool, bool)>());
    println!("enum {{ P(bool), 254 dataless }}: size {}", size_of::<BoolK254>());
    println!("enum {{ P(bool), 255 dataless }}: size {}", size_of::<BoolK255>());
    println!("enum {{ P((bool, bool)), 254 dataless }}: size {}", size_of::<BoolPairK254>());
    println!("enum {{ P((bool, bool)), 255 dataless }}: size {}", size_of::<BoolPairK255>());
}
