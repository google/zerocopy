#!/usr/bin/env python3
"""Toy model: which interleavings does a scheduler generate for nested
parallel composition?

This is a self-contained TOY MODEL written for illustration. It is not a
model of any specific published semantics or tool. It compares three ways of
resolving the nondeterminism of a binary parallel-composition operator:

  full     -- interleaving semantics: any unfinished leaf thread may take the
              next step (the rule "C1 || C2 -> C1' || C2  or  C1 || C2'"
              applied at every nesting level).
  onebit   -- a scheduler that supplies ONE bit per step and passes the SAME
              bit down into every nested parallel node on the path
              (0 = left, 1 = right; a finished side forces the other side).
  pathsel  -- a scheduler that supplies one bit PER parallel node on the
              path (a path selector), i.e. an independent choice at every
              nesting level.

Programs are binary trees of `Par` nodes whose leaves are threads, each a
list of atomic actions. Actions are ("alloc", c), ("free", c) or
("write", c, v). The probe reports, for each scheduler:
  * the number of distinct complete action sequences (traces),
  * the set of final memories,
  * the maximum number of simultaneously allocated cells over all traces
    ("peak"), and
  * traces generated by `full` but not by the scheduler.

Run:  python3 nested_par_schedulers.py
Only the Python standard library is used.
"""

from functools import lru_cache
from itertools import product


# A configuration is a tree: ("leaf", name, pc) or ("par", left, right).
# Program definition uses names; the action table maps name -> actions.

def leaf(name):
    return ("leaf", name, 0)


def par(l, r):
    return ("par", l, r)


def finished(t, prog):
    if t[0] == "leaf":
        return t[2] >= len(prog[t[1]])
    return finished(t[1], prog) and finished(t[2], prog)


def step_leaf(t, prog):
    _, name, pc = t
    return ("leaf", name, pc + 1), (name, prog[name][pc])


def full_successors(t, prog):
    """All (event, t') pairs under interleaving semantics."""
    if t[0] == "leaf":
        if finished(t, prog):
            return []
        nt, ev = step_leaf(t, prog)
        return [(ev, nt)]
    _, l, r = t
    out = []
    for ev, nl in full_successors(l, prog):
        out.append((ev, ("par", nl, r)))
    for ev, nr in full_successors(r, prog):
        out.append((ev, ("par", l, nr)))
    return out


def onebit_step(t, prog, b):
    """One step under the one-bit scheduler; returns (event, t') or None."""
    if t[0] == "leaf":
        if finished(t, prog):
            return None
        nt, ev = step_leaf(t, prog)
        return ev, nt
    _, l, r = t
    lf, rf = finished(l, prog), finished(r, prog)
    if lf and rf:
        return None
    go_left = rf or (not lf and b == 0)
    if go_left:
        res = onebit_step(l, prog, b)  # the SAME bit is passed down
        return None if res is None else (res[0], ("par", res[1], r))
    res = onebit_step(r, prog, b)
    return None if res is None else (res[0], ("par", l, res[1]))


def onebit_successors(t, prog):
    seen = {}
    for b in (0, 1):
        res = onebit_step(t, prog, b)
        if res is not None:
            seen[(res[0], res[1])] = res
    return list(seen.values())


def depth(t):
    return 0 if t[0] == "leaf" else 1 + max(depth(t[1]), depth(t[2]))


def pathsel_step(t, prog, bits):
    if t[0] == "leaf":
        if finished(t, prog):
            return None
        nt, ev = step_leaf(t, prog)
        return ev, nt
    _, l, r = t
    lf, rf = finished(l, prog), finished(r, prog)
    if lf and rf:
        return None
    b, rest = bits[0], bits[1:]
    go_left = rf or (not lf and b == 0)
    if go_left:
        res = pathsel_step(l, prog, rest)
        return None if res is None else (res[0], ("par", res[1], r))
    res = pathsel_step(r, prog, rest)
    return None if res is None else (res[0], ("par", l, res[1]))


def pathsel_successors(t, prog):
    seen = {}
    for bits in product((0, 1), repeat=max(1, depth(t))):
        res = pathsel_step(t, prog, bits)
        if res is not None:
            seen[(res[0], res[1])] = res
    return list(seen.values())


def explore(t0, prog, succ):
    """Enumerate all complete traces with their final memory and peak."""
    results = []  # (trace tuple, final memory frozenset, peak)

    def apply(mem, live, ev):
        _, act = ev
        mem = dict(mem)
        live = set(live)
        if act[0] == "alloc":
            live.add(act[1])
            mem[act[1]] = 0
        elif act[0] == "free":
            live.discard(act[1])
        elif act[0] == "write":
            mem[act[1]] = act[2]
        return mem, live

    def rec(t, trace, mem, live, peak):
        nxt = succ(t, prog)
        if not nxt:
            assert finished(t, prog), "stuck configuration"
            results.append((tuple(trace), frozenset(mem.items()), peak))
            return
        for ev, nt in nxt:
            m2, l2 = apply(mem, live, ev)
            rec(nt, trace + [ev], m2, l2, max(peak, len(l2)))

    rec(t0, [], {}, set(), 0)
    return results


def summarize(label, t0, prog):
    print(f"=== {label}")
    full = explore(t0, prog, full_successors)
    full_traces = {r[0] for r in full}
    for name, succ in (("full", full_successors),
                       ("onebit", onebit_successors),
                       ("pathsel", pathsel_successors)):
        res = explore(t0, prog, succ)
        traces = {r[0] for r in res}
        finals = sorted({tuple(sorted(r[1])) for r in res})
        peak = max(r[2] for r in res)
        missing = sorted(full_traces - traces)
        print(f"{name:8s} traces={len(traces):4d} finals={finals} peak={peak} "
              f"missing_vs_full={len(missing)}")
        if name == "onebit" and missing:
            first = [" ".join(e[0] + ":" + e[1][0] for e in tr) for tr in missing[:3]]
            for f in first:
                print(f"         e.g. missing: {f}")
        assert traces <= full_traces
    print()


def main():
    # Race-free, partitioned program: each thread allocates and frees its
    # own cell. Final memory is the same under every schedule; the peak
    # number of simultaneously live cells is a property of the explored
    # schedules.
    prog_alloc = {
        "a": [("alloc", "x"), ("free", "x")],
        "b": [("alloc", "y"), ("free", "y")],
        "c": [("alloc", "z"), ("free", "z")],
    }
    summarize("(a || b) || c, disjoint alloc/free", par(par(leaf("a"), leaf("b")), leaf("c")), prog_alloc)
    summarize("a || (b || c), disjoint alloc/free", par(leaf("a"), par(leaf("b"), leaf("c"))), prog_alloc)

    # Racy program: three single writes to one cell. Here the set of final
    # memories is the observable.
    prog_race = {
        "a": [("write", "m", 1)],
        "b": [("write", "m", 2)],
        "c": [("write", "m", 3)],
    }
    summarize("(a || b) || c, racy writes", par(par(leaf("a"), leaf("b")), leaf("c")), prog_race)

    # Deeper nesting: ((a || b) || c) || d with one action each.
    prog4 = {k: [("write", k, 1)] for k in "abcd"}
    summarize("((a || b) || c) || d, disjoint writes",
              par(par(par(leaf("a"), leaf("b")), leaf("c")), leaf("d")), prog4)


if __name__ == "__main__":
    main()
